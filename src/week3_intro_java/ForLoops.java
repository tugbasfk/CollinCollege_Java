package week3_intro_java;

public class ForLoops {
    public static void main(String[] args) {


        for (int i = 8; i <= 12; i++) {
            System.out.println(i + " ");
        }

        for (int j = 10; j >= 1; j--) {
            System.out.println(j + " ");
        }

        for (int x = 100; x >= 0; x -= 7) {
            System.out.println(x + " ");
        }


    }
}
